pontos =[]
loop = True

while loop:
 try:
  decisão = int (input("digite os numeros as serem somados para tem a media e digite qualquer letra para parar o programa"))
  if loop == True:
    pontos.append(decisão)
 except ValueError:
  loop =False

def calcular_media(pontos):
  total = 0
  for c in pontos:
    total += c

  Divisor = len(pontos)
  resultado = (total)/Divisor

  return resultado

print(calcular_media(pontos))