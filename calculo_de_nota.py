#dados/definições
def media(a,b,c,d):
  resultado = (a + b + c + d)/4
  return resultado
valores =[]
notas = ["nota 1","nota 2","nota 3","nota 4"]

#codigo
print("""
BEM-VINDO AO PROGRAMA CLASSIFICADO DE NOTAS

DEIXE A NOTA DO ALUNO AQUI QUE FAZEMOS O RESTO \n
""")
for notas in notas:
 notas = int (input(f"insira a {notas} do  aluno 1 a 10: "))

 if  notas >=0 and notas <=10:
  valores.append(notas)
 else:
  print("nota invalida")
  break

resultado_media =media(valores[0],valores[1],valores[2],valores[3])

if resultado_media >=7:
  print(f"notas inseridas: {valores} ,a media {resultado_media} e a situação do aluno aprovado ")
else:
  print(f"notas inseridas: {valores} ,a media {resultado_media} e a situação do aluno reprovado ")

